function [Z, Zp] = ct_zfun(z)
%CT_ZFUN  等离子体色散函数 Z(ζ) 及其导数 Z'(ζ)
%=========================================================================================
% 约定:  Z(ζ) = (1/sqrt(pi)) ∫ dt e^{-t^2}/(t-ζ)  = i*sqrt(pi)*w(ζ),
%        w(ζ) = e^{-ζ^2} erfc(-iζ)  (Faddeeva 函数)。Z 是**整函数**。
%
% 自检:  Z(0) = i*sqrt(pi) = 1.7724538509i ;  Z'(ζ) = -2(1 + ζ Z(ζ)) ;  Z(ζ→∞) → -1/ζ
%
% 两个分支:
%   |z| <= 4 : 用 erf 的 Taylor 级数, 经 w(z) = e^{-z^2}(1 + erf(i z)) 组合
%   |z| >  4 : 直接用 w(z) 的渐近级数并除掉 e^{-z^2} 因子
%                Z(ζ) ~ -(1/ζ) Σ_{m>=0} (2m-1)!!/(2 ζ²)^m
%              这样写是必须的: 若按 e^{-z^2}·erfc(-iz) 计算, Re z 大时 e^{-z^2} 溢出成 Inf,
%              使 D(ω) 变 NaN, 表现为"找不到任何不稳定模式"。渐近级数截断到最小项。
%
% 【与本文档 DGH 说明的关系】
%   二次分母问题(见 ../DGH问题_磁漂移共振二次分母_详解.md)的根源是: 磁漂移含 v∥²,
%   使共振分母对 v∥ 为二次, 于是"沿实轴积分得到的那个函数 f" 在上下半平面并非同一个函数
%   (下半平面相差 2i√π e^{-z²})。**本文件给出的是整函数 Z**, 供色散函数使用;
%   若你自行实现"沿实轴数值积分"的 Z, 请注意该跳跃。
%
% 用法:  [Z, Zp] = ct_zfun(z)
%=========================================================================================

if isreal(z), z = complex(z); end      % 只用 isreal(基础函数)

% ---------------------------------------------------------------------------------------
% 【v7 修正】下半平面 Im z < 0 必须用反射恒等式补上 2i√π e^{-z²} 项
%   Z 是**整函数**; 但上面的渐近级数只对 arg z ∈ (-π/4, 5π/4) 有效, 即"上半平面 + 右下楔形"。
%   在**下半平面**且 |Re z| < |Im z| 的区域, 整函数 Z 的正确渐近行为是
%       Z(z) = 2i√π e^{-z²} - Z(-z) ,  其中 Z(-z) 才落在渐近级数的有效扇区内。
%   v6 无条件用渐近级数, 在这些点上误差 O(1)~(100%)(实测: z=-3-4i 给 0.116-0.161i,
%   正确值 -3520+1649i; z=0.5-4.5i 给 -0.023-0.215i, 正确值 1.7e9-3.6e8i)。
%   注意 |z| <= 4 的 Taylor 分支对**任意** z 都正确(w = e^{-z²}(1+erf(iz)) 是恒等式),
%   所以只有 |z| > 4 且 Im z < 0 才需要反射; 自检 [T23c] 专门守住这一点。
%   下半平面深部 e^{-z²} 可能溢出(Im z ≲ -26) —— 此时 |Z| 本身就 > realmax, 返回 Inf 是
%   数学上一致的(调用方 ct_roots 会把非有限的 D 视为无根)。
% ---------------------------------------------------------------------------------------
if abs(z) <= 4
    w = exp(-z*z)*ct_erfc_negiz(z);
    Z = 1i*sqrt(pi)*w;
elseif imag(z) >= 0
    Z = ct_zasy(z);
else
    zneg = -z;                     % Im(zneg) > 0 → 走稳定分支
    if abs(zneg) <= 4
        Zneg = 1i*sqrt(pi)*exp(-zneg*zneg)*ct_erfc_negiz(zneg);
    else
        Zneg = ct_zasy(zneg);
    end
    Z = 2i*sqrt(pi)*exp(-z*z) - Zneg;
end

if nargout > 1
    Zp = -2*(1 + z*Z);
end
end

% ---------------------------------------------------------------------------------------
function Z = ct_zasy(z)
%CT_ZASY  |z| > 4 且 Im z >= 0 时的渐近级数 Z(z) ~ -(1/z)Σ(2m-1)!!/(2z²)^m (截断到最小项)
z2 = z*z;
s = 1;  term = 1;  bestS = 1;  bestMag = 1;
for m = 1:60
    term = term*((2*m-1)/2);
    t = term/z2^m;
    s = s + t;
    mag = abs(t);
    if mag < bestMag, bestMag = mag; bestS = s; end
    if mag < 1e-18 || mag > bestMag, break; end
end
Z = -bestS/z;
end

% ---------------------------------------------------------------------------------------
function v = ct_erfc_negiz(z)
% erfc(-i z) = 1 + erf(i z), 用 erf 的 Taylor 级数(收敛, |z| <= 4)
w  = 1i*z;
wp = w;  w2 = w*w;  s = 0;
for n = 0:100
    term = wp/(factorial(n)*(2*n+1));
    s = s + (-1)^n*term;
    wp = wp*w2;
    if abs(term) < 1e-19*max(1,abs(s)), break; end
end
v = 1 + (2/sqrt(pi))*s;
end
