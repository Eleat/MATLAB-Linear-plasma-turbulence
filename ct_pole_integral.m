function [I, u_star] = ct_pole_integral(omega, C, eta)
%CT_POLE_INTEGRAL  单极点约化的速度空间积分(本文档 PDF §7.3–7.5)
%=========================================================================================
% 计算
%     I = (2/sqrt(pi)) * (1/C) * ∫_0^∞ du  sqrt(u) e^{-u} [1 + eta (u - 3/2)] / (u - u_*)
%     u_* = omega / C
%
% 这是 PDF 中式 (7.3) 的积分: 把环形漂移写成 omega_Ds ≈ C u (u = x² = v²/v_t², C = ω_D0 c_D),
% 并略去共振分母中的 k∥ v∥, 于是整个速度空间积分塌缩为**单个极点** u_* 的留数 + 主值。
%
% ------------------------------- 数值方法 -------------------------------
% 不使用主值积分, 而用**减去极点**的恒等式(对该积分精确):
%
%   ∫_0^U du h(u)/(u-u_*) = ∫_0^U du [h(u)-h(u_*)]/(u-u_*)  +  h(u_*) [ln(U-u_*) - ln(-u_*)]
%
% 第一项在 u = u_* 处是**可去奇点**(分子同时为零), 且 u_* 是复数、积分变量 u 是实数,
% 故 u - u_* 在积分路径上不为零 —— 无需主值处理, 也无需在极点附近加密网格。
% 第二项给出解析的有限部分。取 U = 40 (h(40) ~ 1e-15, 可忽略)。
%
% **朗道解析延拓**(v4 修正): 物理区为 Im ω > 0, 故 Im u_* = Im ω/C 的"物理侧"由 sc = sign(C) 定出。
% 只有当极点落在割线 [0,∞) 内(Re u_* > 0, 即分布函数支撑区)时, 实轴两侧才分属不同支, 才需要换支:
%     I_phys = I_该侧 + sc*2*pi*i*h(u_*),   当 sign(Im u_*) ~= sc .
% 【旧写法的两个漏洞】(见自检 [T4b] 与 §9.3)
%   ① 只判 Im u_* <= 0 而不管 Re u_*: Re u_* < 0 时极点根本不在割线上, F 在该点解析、
%      实轴两侧同值, 补项会加进 O(2π|h|) 的假贡献(单极点模型的离子通道正是这种情形);
%   ② 换支方向恒取 +2πi: C < 0 时物理侧在下半平面, 方向必须反过来(乘 sc), 否则阻尼侧错。
% 这与"整函数 vs 沿实轴积分"的跳跃是同一件事 (见 ../DGH问题_..._详解.md 附录 B)。
% 数值判据: ct_selftest [T4b] 要求 I 在实轴两侧连续(Re u_*=±3 各一对点)。
%
% ------------------------------- 输出 -------------------------------
%   I       : 复数
%   u_star  : 极点位置 (= omega/C), 供 C_T 提取使用
%
% 用法:  [I, u_star] = ct_pole_integral(omega, C, eta)
%=========================================================================================

U = 40;
u_star = omega/C;

h  = @(u) sqrt(max(u,0)).*exp(-u).*(1 + eta*(u - 1.5));
hS = h(u_star);                 % 极点上的核(复值): 使被积函数在u≈u_*处光滑(任意常数都精确, 此选择数值条件最好)

% ---- 第一项: 可去奇点的光滑积分 ----
% 始终用几何加密: 极点附近被积函数的变化尺度是 max(|Im u_*|, 1), 均匀网格会欠分辨。
integrand = @(u) (h(u) - hS)./(u - u_star);
core = ct_gl_graded(integrand, 0, U, real(u_star), max(abs(imag(u_star)), 0.05));

% ---- 第二项: 解析的有限部分 ----
finite = hS*(log(U - u_star) - log(-u_star));

val = core + finite;

% ---- 朗道解析延拓: 把"直接求积得到的那一侧"换算回物理支 ----
% 【规则】(v4 修正, 见 §9.3)  记 sc = sign(C)。物理区是 Im ω > 0, 故 Im u_* = Im ω/C 的物理侧是
%   sign(Im u_*)|_phys = sc。只有当极点落在**分布函数支撑区**(Re u_* > 0, 即 u_* 平面的割线 [0,∞),
%   文档① §7.5)上时, 实轴两侧才分属不同支, 才需要用 ±2πi h(u_*) 换支:
%       若 sign(Im u_*) ~= sc(含 Im u_* = 0)  =>  val = val + sc*2i*pi*h(u_*)
%   两条缺失条件都会造成**没有物理对应的假贡献**:
%     ① Re u_* < 0 时 F 在实轴两侧本来就连续(该点不在割线上, 判据见自检 [T4b] 的数值实验),
%        此时补项会凭空加进 O(2π|h|) —— 单极点模型的离子通道 C_i = -(4/3)λ_iω_D0i < 0
%        且 ω_r > 0 => Re u_*i < 0, 恰好被误补(实测 |D| 在 kinetic 根处由 0.48 变成 3.3e3)。
%     ② C < 0 时物理侧在下半平面(不是上半), 换支方向要反过来(乘 sc = -1), 否则阻尼侧会错。
if real(u_star) > 0
    sc = sign(real(C));
    if sc ~= 0 && sign(imag(u_star))*sc <= 0
        val = val + sc*2i*pi*h(u_star);
    end
end

I = (2/sqrt(pi))*val/C;
end

% ---------------------------------------------------------------------------------------
function s = ct_gl_quad(f, a, b, np)
% [a,b] 上 np 个面板 x 32 点 Gauss-Legendre
[xg, wg] = ct_gaussleg(32, -1, 1);
hstep = (b - a)/np;
s = 0;
for p = 0:np-1
    c = a + (p + 0.5)*hstep;  d = hstep/2;
    s = s + sum(wg.*f(c + d*xg))*d;
end
end

% ---------------------------------------------------------------------------------------
function s = ct_gl_graded(f, a, b, x0, delta)
% 在 x0 附近按几何级数加密断点的复合 32 点 Gauss-Legendre。
% 面板预算 ~260 按区间宽度分配, 因此极点附近自动获得细面板。
br = [a, b];
for m = [1 2 4 8 16 32 64 128]
    if x0 - m*delta > a && x0 - m*delta < b, br = [br, x0 - m*delta]; end
    if x0 + m*delta > a && x0 + m*delta < b, br = [br, x0 + m*delta]; end
end
if x0 > a && x0 < b, br = [br, x0]; end
br = sort(br);
NPANEL = 260;
s = 0;
for ii = 1:numel(br)-1
    wdt = br(ii+1) - br(ii);
    s = s + ct_gl_quad(f, br(ii), br(ii+1), max(3, round(NPANEL*wdt/(b - a))));
end
end
