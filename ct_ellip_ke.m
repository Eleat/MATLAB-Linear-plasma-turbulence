function [Kk, Ek] = ct_ellip_ke(m)
%CT_ELLIP_KE  第一/二类完全椭圆积分 K(m)、E(m), 参数 m = κ² ∈ [0,1] —— AGM 算法
%=========================================================================================
% 弹跳平均(文档① §9.4)要用到
%     ⟨cosθ⟩_b = 2E(κ)/K(κ) - 1,
%     ⟨cos²θ⟩_b = 1 - 4⟨s²⟩_b + 4⟨s⁴⟩_b,   ⟨s²⟩_b = (K-E)/K,  ⟨s⁴⟩_b = κ⁴I₂/K,
%     I₂ = [2(1+κ²)I₁ - K]/(3κ²),   I₁ = (K-E)/κ²
% (最后两式是 ∫₀^{π/2} sin^{2n}φ/√(1-κ²sin²φ)dφ 的递推, 已用 4000 点求积逐点验证到 1e-8;
%  ⟨cos²θ⟩_b 在 κ→1 时趋于 1 但极慢(对数收敛), 因此 κ 接近 1 处数值上仍是 O(0.5)。)
%
% 用 AGM(算术-几何平均)算 K、E: 对 κ→1 也稳定, 无奇异积分:
%     a₀=1, b₀=√(1-m), c₀=√m;  a_{n+1}=(a_n+b_n)/2, b_{n+1}=√(a_n b_n), c_{n+1}=(a_n-b_n)/2
%     K = π/(2a_∞),   E = K·(1 - Σ_{n≥1} 2^{n-1} c_n²)
% 极限: K(0)=E(0)=π/2;  K(1)=∞(对数发散), E(1)=1。
% 标准值校验(自检 [T20a]): K(0.5)=1.8540746773013719, E(0.5)=1.3506438810476755。
%=========================================================================================

m = min(max(m, 0), 1);
if m <= 0
    Kk = pi/2;  Ek = pi/2;  return;
end
if m >= 1
    Kk = Inf;   Ek = 1;     return;
end
a = 1;  b = sqrt(1 - m);  c = sqrt(m);
s = m/2;                       % Σ 2^{n-1} c_n² 的首项(n=0, 2^{-1}c₀² = m/2)
p = 1;
for n = 1:30
    an = (a + b)/2;  bn = sqrt(a*b);  cn = (a - b)/2;
    a = an;  b = bn;  c = cn;
    s = s + p*c*c;
    p = 2*p;
    if c < 1e-16, break; end
end
Kk = pi/(2*a);
Ek = Kk*(1 - s);
end
